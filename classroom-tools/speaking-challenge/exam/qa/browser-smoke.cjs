const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const url = process.argv[2] || 'http://127.0.0.1:8768/exam/';
  const report = { url, checkedAt: new Date().toISOString(), checks: [], pageErrors: [] };
  const output = process.argv[3] ? path.resolve(process.argv[3]) : __dirname;
  fs.mkdirSync(output, { recursive: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    page.on('pageerror', error => report.pageErrors.push(error.message));
    await page.clock.install();
    await page.clock.pauseAt(new Date());
    await page.goto(url);
    await page.waitForFunction(() => !document.querySelector('#mainAction').disabled);
    assert.equal(await page.locator('#mainAction').innerText(), '开始抽题');
    assert.equal(await page.locator('h1').innerText(), '口语练习');
    assert.deepEqual(await page.evaluate(() => ({ questions: window.ORAL_EXAM_BANK.questions.length, pictures: window.ORAL_EXAM_BANK.pictures.length })), { questions: 30, pictures: 12 });
    await page.screenshot({ path: path.join(output, 'ready-desktop.png'), fullPage: true });
    report.checks.push('30 questions and 12 decoded local images load');
    await page.evaluate(() => {
      window.revealObservations = [];
      new MutationObserver(() => {
        const q = document.querySelector('.question-prompt');
        const p = document.querySelector('.picture-visual');
        if (q || p) window.revealObservations.push({ question: !!q, picture: !!p, decoded: !!p?.naturalWidth });
      }).observe(document.querySelector('.exam-grid'), { childList: true, subtree: true });
    });
    await page.locator('#mainAction').click();
    assert.equal(await page.locator('.is-shuffling').count(), 2);
    assert.equal(await page.locator('#mainAction').isDisabled(), true);
    await page.screenshot({ path: path.join(output, 'drawing-desktop.png'), fullPage: true });
    await page.clock.runFor(1700);
    assert.match(await page.locator('#questionTag').innerText(), /^问题 A(0[1-9]|[12][0-9]|30)$/);
    assert.match(await page.locator('#pictureTag').innerText(), /^图片 B(0[1-9]|1[0-2])$/);
    assert.equal(await page.locator('#mainAction').innerText(), '开始准备');
    const observations = await page.evaluate(() => window.revealObservations);
    assert.ok(observations.length && observations.every(x => x.question && x.picture && x.decoded));
    report.checks.push('valid random pair, animation lock, atomic decoded reveal');
    await page.screenshot({ path: path.join(output, 'revealed-desktop.png'), fullPage: true });
    const originalPair = await page.locator('.item-tag').allTextContents();
    await page.locator('#mainAction').click();
    assert.equal(await page.locator('#timer').innerText(), '01:00');
    await page.clock.runFor(1000);
    assert.equal(await page.locator('#timer').innerText(), '00:59');
    await page.locator('#pauseAction').click();
    await page.clock.runFor(20000);
    assert.equal(await page.locator('#timer').innerText(), '00:59');
    await page.locator('#pauseAction').click();
    await page.clock.runFor(59000);
    assert.equal(await page.locator('#phaseLabel').innerText(), '回答剩余');
    assert.equal(await page.locator('#timer').innerText(), '02:00');
    await page.screenshot({ path: path.join(output, 'speaking-desktop.png'), fullPage: true });
    await page.clock.runFor(119000);
    assert.equal(await page.locator('#timer').innerText(), '00:01');
    await page.clock.runFor(1000);
    assert.equal(await page.locator('#timer').innerText(), '00:00');
    assert.equal(await page.locator('#mainAction').innerText(), '再练一题');
    assert.deepEqual(await page.locator('.item-tag').allTextContents(), originalPair);
    report.checks.push('60s preparation then automatic 120s response, pause/resume, both cards remain');
    await page.locator('#mainAction').click();
    assert.equal(await page.locator('.is-shuffling').count(), 2);
    await page.clock.runFor(1700);
    assert.equal(await page.locator('#mainAction').innerText(), '开始准备');
    report.checks.push('one-click repeat practice draws a fresh pair');
    await page.locator('#mainAction').click();
    await page.clock.fastForward(181000);
    assert.equal(await page.locator('#mainAction').innerText(), '再练一题');
    report.checks.push('background-style clock jump catches up across both deadlines');
    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
    await mobile.goto(url);
    await mobile.waitForFunction(() => !document.querySelector('#mainAction').disabled);
    await mobile.locator('#mainAction').click();
    await mobile.waitForSelector('.picture-visual');
    assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await mobile.screenshot({ path: path.join(output, 'revealed-mobile.png'), fullPage: true });
    report.checks.push('mobile no horizontal overflow; reduced-motion reveal');
    const laptop = await browser.newPage({ viewport: { width: 1280, height: 720 }, reducedMotion: 'reduce' });
    await laptop.goto(url);
    await laptop.waitForFunction(() => !document.querySelector('#mainAction').disabled);
    await laptop.locator('#mainAction').click();
    await laptop.waitForSelector('.picture-visual');
    assert.ok(await laptop.evaluate(() => {
      const image = document.querySelector('.picture-visual').getBoundingClientRect();
      const body = document.querySelector('#pictureCardBody').getBoundingClientRect();
      return document.documentElement.scrollHeight <= innerHeight && image.bottom <= body.bottom && image.top >= body.top;
    }));
    await laptop.screenshot({ path: path.join(output, 'revealed-laptop.png'), fullPage: true });
    report.checks.push('1280x720 laptop fits both panels, image and controls without clipping');
    const offline = await browser.newPage();
    await offline.goto('file://' + path.resolve(__dirname, '../index.html'));
    await offline.waitForFunction(() => !document.querySelector('#mainAction').disabled);
    await offline.locator('#mainAction').click();
    await offline.waitForSelector('.picture-visual');
    report.checks.push('file:// offline launch and local picture load');
    const broken = await browser.newPage();
    await broken.route('**/assets/B12.webp', route => route.abort());
    await broken.goto(url);
    await broken.waitForFunction(() => document.querySelector('#mainAction').textContent === '无法开始');
    assert.equal(await broken.locator('#mainAction').isDisabled(), true);
    assert.match(await broken.locator('#examStatus').innerText(), /B12/);
    report.checks.push('missing picture prevents draw and reports file');
    assert.deepEqual(report.pageErrors, []);
    report.status = 'passed';
  } catch (error) {
    report.status = 'failed';
    report.error = error.stack;
    throw error;
  } finally {
    fs.writeFileSync(path.join(output, 'browser-verification.json'), JSON.stringify(report, null, 2) + '\n');
    await browser.close();
    console.log(JSON.stringify(report, null, 2));
  }
})().catch(() => { process.exitCode = 1; });
