class DeckPages(HTMLParser):
    def __init__(self):
        super().__init__()
        self.count = 0
        self.starts = []

    def handle_starttag(self, tag, attrs):
        if 'os-page' in dict(attrs).get('class', '').split():
            self.count += 1
            self.starts.append(self.getpos())


def page_count(html):
    parser = DeckPages()
    parser.feed(html)
    if not parser.count or 'window.__classroomDeck' not in html:
        raise ValueError('Expected an OpenSlide classroom HTML deck with page navigation')
    return parser.count


def inside(path, boundary):
    resolved = path.resolve()
    if not resolved.is_relative_to(boundary.resolve()) or resolved == boundary.resolve():
        raise ValueError(f'Path outside allowed directory: {path}')
    return resolved


def file_sha256(path):
    digest = hashlib.sha256()
    with path.open('rb') as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def check_visual_profile(deck, source):
    profile = deck.get('visual_check')
    if profile is None:
        legacy = LEGACY_VISUAL_BASELINES.get(deck.get('id'))
        relative_source = source.relative_to(ROOT).as_posix()
        if legacy and legacy[0] == relative_source and file_sha256(source) == legacy[1]:
            return f'legacy baseline unchanged ({legacy[1]})'
        raise ValueError(f"{deck.get('id')}: visual_check profile is required before OpenSlide sync")
    if not isinstance(profile, dict):
        raise ValueError(f"{deck.get('id')}: visual_check must be an object")
    reference_value = profile.get('reference')
    expected_reference_hash = profile.get('reference_sha256')
    expected_route_cards = profile.get('expected_route_cards')
    expected_route_columns = profile.get('expected_route_columns')
    expected_page_types = profile.get('page_types')
    required_page_types = {'discussion', 'comic', 'report'}
    if (
        not isinstance(reference_value, str)
        or not isinstance(expected_reference_hash, str)
        or not re.fullmatch(r'[0-9a-f]{64}', expected_reference_hash)
        or type(expected_route_cards) is not int
        or expected_route_cards < 1
        or type(expected_route_columns) is not int
        or expected_route_columns < 1
        or not isinstance(expected_page_types, dict)
        or set(expected_page_types) != required_page_types
        or any(
            not isinstance(ids, list)
            or any(not isinstance(stable_id, str) or not stable_id for stable_id in ids)
            or len(ids) != len(set(ids))
            for ids in expected_page_types.values()
        )
    ):
        raise ValueError(
            f"{deck.get('id')}: visual_check needs a project-relative reference, its SHA-256, positive expected_route_cards and expected_route_columns, "
            "and explicit discussion/comic/report page ID lists"
        )
    reference = inside(ROOT / reference_value, ROOT)
    if not reference.is_file():
        raise ValueError(f"{deck.get('id')}: visual reference does not exist: {reference_value}")
    if reference == source:
        raise ValueError(f"{deck.get('id')}: visual reference must be a separate, stable deck")
    if file_sha256(reference) != expected_reference_hash:
        raise ValueError(f"{deck.get('id')}: visual reference SHA-256 changed; review and update the profile before syncing")
    errors = VISUAL_CHECKER.check(
        source,
        reference,
        expected_route_cards=expected_route_cards,
        expected_page_types=expected_page_types,
        expected_route_columns=expected_route_columns,
        content_contract=inside(ROOT / profile['content_contract'], ROOT) if profile.get('content_contract') else None,
    )
    if errors:
        details = '\n'.join(f'  - {error}' for error in errors)
        raise ValueError(f"{deck.get('id')}: OpenSlide visual regression check failed:\n{details}")
    contract_value = profile.get('content_contract')
    if not isinstance(contract_value, str):
        raise ValueError(f"{deck.get('id')}: content_contract is required before OpenSlide sync")
    contract_path = inside(ROOT / contract_value, ROOT)
    contract = json.loads(contract_path.read_text())
    check_registered_identity(deck, source, profile, contract)
    report_value = profile.get('rendered_layout_report')
    if not isinstance(report_value, str):
        raise ValueError(f"{deck.get('id')}: rendered_layout_report is required before OpenSlide sync")
    report_path = inside(ROOT / report_value, ROOT)
    if not report_path.is_file():
        raise ValueError(f"{deck.get('id')}: rendered layout report missing: {report_value}")
    report = json.loads(report_path.read_text())
    checker = ROOT / 'scripts/check_open_slide_rendered_layout.cjs'
    if report.get('deck_sha256') != file_sha256(source) or report.get('checker_sha256') != file_sha256(checker):
        raise ValueError(f"{deck.get('id')}: rendered layout report is stale; rerender the current HTML")
    pages = report.get('pages', [])
    expected_ids = [p['id'] for p in contract.get('pages', [])]
    if (report.get('schema_version') != 2 or report.get('contract_sha256') != file_sha256(contract_path)
            or not isinstance(pages, list) or len(pages) != page_count(source.read_text())
            or [p.get('id') for p in pages] != expected_ids or report.get('errors') != []
            or any(p.get('issues') != [] or not p.get('structure') or not p.get('coverage')
                   or not p.get('text_runs') or not p.get('screenshot', {}).get('sha256') for p in pages)):
        raise ValueError(f"{deck.get('id')}: rendered layout report failed, incomplete or not bound to the page contract")
    node = shutil.which('node')
    if node is None:
        raise ValueError('Installed Node.js is required for fresh rendered verification; no browser check ran')
    result = subprocess.run(
        [node, str(checker), '--deck', str(source), '--contract', str(contract_path), '--verify-report', str(report_path)],
        cwd=ROOT, capture_output=True, text=True, timeout=90,
    )
    if result.returncode:
        raise ValueError(f"{deck.get('id')}: fresh rendered verification failed: {(result.stdout + result.stderr).strip()}")
    return f'copy contract and fresh rendered visual checks passed ({file_sha256(source)})'


def check_registered_identity(deck, source, profile, contract):
    """Bind preview routing to the same lesson/copy identity as the draft."""
    owner = contract.get('owner_lesson_key')
    lesson_keys = contract.get('lesson_keys')
    offering = contract.get('offering_id')
    if (deck.get('lesson_key') != owner or deck.get('lesson_keys', [deck.get('lesson_key')]) != lesson_keys
            or deck.get('offering_id') != offering):
        raise ValueError(f"{deck.get('id')}: lesson identity differs from the reviewed page contract")
    if any(not isinstance(p.get('expected_images'), list) or any(not isinstance(x, str) for x in p['expected_images']) for p in contract.get('pages', [])):
        raise ValueError('Every production contract page must declare its approved image mapping, including empty lists')
    route = next((p for p in contract.get('pages', []) if p.get('role') == 'route'), {})
    route_reference = contract.get('references', {}).get('route', {})
    if (profile.get('expected_route_cards') != route.get('expected_route_cards')
            or profile.get('expected_route_columns') != route.get('expected_route_columns')
            or profile.get('reference') != route_reference.get('path')
            or profile.get('reference_sha256') != route_reference.get('sha256')):
        raise ValueError('Visual profile route mapping differs from the reviewed page contract')
    registry = json.loads((ROOT / 'course/lesson-registry.json').read_text())
    records = {x['lesson_key']: x for x in registry['lessons']}
    if not lesson_keys or owner not in lesson_keys or any(k not in records for k in lesson_keys):
        raise ValueError('Unknown lesson identity in classroom slide profile')
    if not source.is_relative_to(ROOT / records[owner]['lesson_path'] / '10-design/open-slide-draft'):
        raise ValueError('Classroom source path does not belong to the declared owner lesson')
    manifest_value = profile.get('draft_manifest')
    if not isinstance(manifest_value, str):
        raise ValueError('A lesson-local draft_manifest is required for classroom identity checking')
    manifest_path = inside(ROOT / manifest_value, source.parent)
    manifest = json.loads(manifest_path.read_text())
    if (manifest.get('lesson_keys') != lesson_keys or manifest.get('offering_id') != offering
            or inside(manifest_path.parent / manifest.get('entry_file', ''), source.parent) != source):
        raise ValueError('Draft manifest and registered lesson/source identity differ')
    approval_records = deck.get('approval_records')
    class_scope = deck.get('class_scope')
    if approval_records is None:
        if LEGACY_APPROVAL_SCOPES.get(deck.get('id')) != (offering, tuple(lesson_keys)):
            raise ValueError('New classroom decks require explicit per-lesson scoped approval records')
    elif (not isinstance(approval_records, dict) or set(approval_records) != set(lesson_keys)
          or any(not isinstance(value, str) or not value for value in approval_records.values())
          or not isinstance(class_scope, str) or not class_scope.strip()
          or contract.get('class_scope') != class_scope or manifest.get('class_scope') != class_scope):
        raise ValueError('Scoped classroom approvals must match every lesson and the exact class scope')
    if approval_records is not None:
        source_path, _ = resolve_relative_path(ROOT, deck.get('source'), required_root=ROOT / records[owner]['lesson_path'] / '10-design/open-slide-draft')
        expected_dir = _safe_project_path(ROOT / records[owner]['lesson_path'] / '10-design/open-slide-draft', f"{offering}/{deck['id']}")
        if source_path.parent != expected_dir:
            raise ValueError('Scoped classroom deck must be in its offering and artifact-specific directory')
    for key in lesson_keys:
        if offering not in records[key].get('offering_ids', []):
            raise ValueError(f'Lesson {key} does not belong to offering {offering}')
        command = [sys.executable, str(ROOT / 'scripts/production_gate.py'), '--purpose', 'content-approval',
                   '--lesson-key', key, '--offering-id', offering]
        if approval_records is not None:
            command += ['--approval-record', approval_records[key], '--artifact-scope', 'classroom',
                        '--artifact-id', deck['id'], '--class-scope', class_scope]
        result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, timeout=30)
        if result.returncode or json.loads(result.stdout).get('status') != 'ready':
            raise ValueError(f'{key}: content approval preflight failed: {(result.stdout + result.stderr).strip()}')


def embed_images(source, active_page=None):
    html = source.read_text()
    parser = DeckPages()
    parser.feed(html)
    lines = html.splitlines(keepends=True)
    offsets = [0]
    for line in lines:
        offsets.append(offsets[-1] + len(line))
    starts = [offsets[line - 1] + column for line, column in parser.starts]
    def embed(match):
        name = match[2]
        if active_page is not None and bisect_right(starts, match.start()) - 1 != active_page:
            return f'{match[1]}data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7{match[3]}'
        if name.startswith('data:'):
            return match[0]
        asset = inside(source.parent / name, source.parent)
        mime = mimetypes.guess_type(asset.name)[0]
        if not mime or not mime.startswith('image/'):
            raise ValueError(f'Expected local image: {name}')
        data = base64.b64encode(asset.read_bytes()).decode('ascii')
        return f'{match[1]}data:{mime};base64,{data}{match[3]}'
    return re.sub(r'(<img\b[^>]*\bsrc=["\'])([^"\']+)(["\'])', embed,
                  html, flags=re.IGNORECASE)


def adapt_html(html):
    # Keep initialization and image loading out of the visible entry animation.
    html, replaced = re.subn(r'(?m)^(\s*)go\(0\);',
                            r"\1go(Number(new URLSearchParams(location.search).get('os-page')));", html)
    if replaced != 1:
        raise ValueError('Expected exactly one classroom initialization call')
    html = html.replace('</head>', '''<style>
html.os-loading body { opacity: 0 !important; }
html.os-loading *, html.os-static * { animation: none !important; transition: none !important; }
</style><script>
document.documentElement.classList.add('os-loading');
if (new URLSearchParams(location.search).get('os-static') === '1')
  document.documentElement.classList.add('os-static');
</script></head>''')
    return html.replace('</body>', '''<style>.os-controls,.os-counter,.os-controlbar{display:none!important}</style>
<script>
window.addEventListener('load', function () {
  var page = Number(new URLSearchParams(location.search).get('os-page'));
  var pages = document.querySelectorAll('.os-page');
  if (!Number.isInteger(page) || page < 0 || page >= pages.length)
    throw new Error('Invalid classroom page');
  window.__classroomDeck.go(page);
  var active = pages[page];
  active.classList.remove('deck-enter');
  document.documentElement.classList.remove('os-loading');
  void active.offsetWidth;
  active.classList.add('deck-enter');
});
</script></body>''')


def select_decks(decks, deck_id=None):
    if deck_id is None:
        return decks
    selected = [deck for deck in decks if deck.get('id') == deck_id]
    if len(selected) != 1:
        raise ValueError(f'Expected one registered deck: {deck_id}')
    return selected


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check-only', action='store_true', help='validate every registered deck without writing workspace files')
    parser.add_argument('--deck-id', help='Validate and sync only this registered deck; leave other previews unchanged')
    args = parser.parse_args(argv)
    registry = json.loads((ROOT / 'course/open-slide-workspace.json').read_text())
    registry['html_decks'] = select_decks(registry['html_decks'], args.deck_id)
    workspace = inside(ROOT / registry['workspace'], ROOT)
    seen = set()
    visual_statuses = {}
    # Validate every source before writing any generated preview, so a later
    # failing profile cannot leave the workspace half-updated.
    for deck in registry['html_decks']:
        deck_id = deck['id']
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', deck_id) or deck_id in seen:
            raise ValueError(f'Invalid or duplicate deck ID: {deck_id}')
        seen.add(deck_id)
        source = inside(ROOT / deck['source'], ROOT / 'lessons')
        if not source.is_file():
            raise ValueError(f'Missing registered HTML source: {source}')
        visual_statuses[deck_id] = check_visual_profile(deck, source)
    if args.check_only:
        for deck_id, status in visual_statuses.items():
            print(f'{deck_id}: {status}')
        print(f'PASS: visual profiles for {len(visual_statuses)} registered HTML decks; no workspace files written')
        return

    seen.clear()
    for deck in registry['html_decks']:
        deck_id = deck['id']
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', deck_id) or deck_id in seen:
            raise ValueError(f'Invalid or duplicate deck ID: {deck_id}')
        seen.add(deck_id)
        source = inside(ROOT / deck['source'], ROOT / 'lessons')
        output = inside(workspace / 'slides' / deck_id, workspace / 'slides')
        entry = inside(output / 'index.tsx', output)
        if entry.exists() and not entry.read_text().startswith(MARKER):
            raise ValueError(f'Refusing to overwrite authored slide: {entry}')
        count = page_count(source.read_text())
        # Keep source scripts and CSS isolated while exposing every page to the player.
        assets = inside(output / 'assets', output)
        assets.mkdir(parents=True, exist_ok=True)
        for index in range(count):
            bundle = inside(assets / f'page-{index + 1:02d}.html', assets)
            bundle.write_text(adapt_html(embed_images(source, index)))
        title = json.dumps(re.sub(r'(?<=（)\d+(?= 页)', str(count), deck['title']), ensure_ascii=False)
        created = json.dumps(deck['created_at'])
        entry.write_text(f'''{MARKER}
import type {{ Page, SlideMeta }} from '@open-slide/core';
import {{ useLayoutEffect, useRef, useState }} from 'react';
const htmlUrls = [{', '.join(f'new URL("./assets/page-{index + 1:02d}.html", import.meta.url).href' for index in range(count))}];

export const meta: SlideMeta = {{ title: {title}, createdAt: {created} }};
// shortcut: isolated HTML pages support player navigation; edit text in the source HTML.
const pages: Page[] = Array.from({{ length: {count} }}, (_, index) => {{
  const Page: Page = () => {{
    const ref = useRef<HTMLDivElement>(null);
    const [frozen, setFrozen] = useState<boolean | null>(null);
    useLayoutEffect(() => {{
      setFrozen(!!ref.current?.closest('[data-osd-freeze-motion]'));
    }}, []);
    return <div ref={{ref}} style={{{{ width: '100%', height: '100%' }}}}>
      {{frozen !== null && <iframe title={{`${{{title}}} — ${{index + 1}}`}}
        src={{`${{htmlUrls[index]}}?os-page=${{index}}&os-static=${{frozen ? 1 : 0}}`}} sandbox="allow-scripts" tabIndex={{-1}}
        style={{{{ width: '100%', height: '100%', border: 0, display: 'block', pointerEvents: 'none' }}}} />}}
    </div>;
  }};
  return Page;
}});
export default pages;
''')
        print(f'{deck_id}: synced {count} pages from {source.relative_to(ROOT)}; {visual_statuses[deck_id]}')


if __name__ == '__main__':
    main()
