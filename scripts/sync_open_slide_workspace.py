#!/usr/bin/env python3
"""Refresh registered HTML deck previews in the shared OpenSlide workspace."""
import base64
import json
import mimetypes
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = '// Generated by sync_open_slide_workspace.py; edit the registered source.'


def inside(path, boundary):
    resolved = path.resolve()
    if not resolved.is_relative_to(boundary.resolve()) or resolved == boundary.resolve():
        raise ValueError(f'Path outside allowed directory: {path}')
    return resolved


def embed_images(source):
    def embed(match):
        name = match[2]
        if name.startswith('data:'):
            return match[0]
        asset = inside(source.parent / name, source.parent)
        mime = mimetypes.guess_type(asset.name)[0]
        if not mime or not mime.startswith('image/'):
            raise ValueError(f'Expected local image: {name}')
        data = base64.b64encode(asset.read_bytes()).decode('ascii')
        return f'{match[1]}data:{mime};base64,{data}{match[3]}'
    return re.sub(r'(<img\b[^>]*\bsrc=["\'])([^"\']+)(["\'])', embed,
                  source.read_text(), flags=re.IGNORECASE)


def main():
    registry = json.loads((ROOT / 'course/open-slide-workspace.json').read_text())
    workspace = inside(ROOT / registry['workspace'], ROOT)
    seen = set()
    for deck in registry['html_decks']:
        deck_id = deck['id']
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', deck_id) or deck_id in seen:
            raise ValueError(f'Invalid or duplicate deck ID: {deck_id}')
        seen.add(deck_id)
        source = inside(ROOT / deck['source'], ROOT / 'lessons')
        output = inside(workspace / 'slides' / deck_id, workspace / 'slides')
        entry = output / 'index.tsx'
        if entry.exists() and not entry.read_text().startswith(MARKER):
            raise ValueError(f'Refusing to overwrite authored slide: {entry}')
        html = embed_images(source)
        assets = inside(output / 'assets', output)
        assets.mkdir(parents=True, exist_ok=True)
        bundle = inside(assets / 'deck.html', assets)
        bundle.write_text(html)
        title = json.dumps(deck['title'], ensure_ascii=False)
        created = json.dumps(deck['created_at'])
        entry.write_text(f'''{MARKER}
import type {{ Page, SlideMeta }} from '@open-slide/core';
import html from './assets/deck.html?raw';

export const meta: SlideMeta = {{ title: {title}, createdAt: {created} }};
// shortcut: HTML decks use their own page controls; use native pages for inspector editing.
const Deck: Page = () => <iframe title={{{title}}} srcDoc={{html}}
  sandbox="allow-scripts" allowFullScreen
  style={{{{ width: '100%', height: '100%', border: 0, display: 'block' }}}} />;
export default [Deck] satisfies Page[];
''')
        print(f'{deck_id}: synced {source.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
