#!/usr/bin/env node
/**
 * Re-render slide screenshots and rebuild legacy slides-data.js.
 *
 * This is retained for compatibility with older QA workflows. The current
 * presenter exports PDFs live and does not use slides-data.js.
 *
 * Usage:
 *   node scripts/build-slides-data.mjs --slides-dir output/book-1/lesson-01/slides
 *   node scripts/build-slides-data.mjs --slides-dir output/book-1/lesson-02/slides --no-render
 *
 * Options:
 *   --slides-dir <path>   Path to the slides directory (required)
 *   --no-render           Skip screenshot rendering, only rebuild legacy slides-data.js
 */
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { chromium } from 'playwright';

const root = process.cwd();

// Parse CLI args
const args = process.argv.slice(2);
const slidesDirArg = args[args.indexOf('--slides-dir') + 1];
const renderScreenshots = !args.includes('--no-render');

if (!slidesDirArg) {
  console.error('Error: --slides-dir <path> is required');
  console.error('Example: node scripts/build-slides-data.mjs --slides-dir output/book-1/lesson-01/slides');
  process.exit(1);
}

const slidesDir = path.resolve(root, slidesDirArg);
const lessonRoot = path.dirname(slidesDir);
const screenshotsDir = path.join(lessonRoot, 'exports', 'qa', 'screenshots');
const outFile = path.join(lessonRoot, 'exports', 'archive', 'slides-data.js');
const indexFile = path.join(slidesDir, 'index.html');
const width = 1920;
const height = 1080;
const scale = 2;

if (!fs.existsSync(slidesDir)) {
  console.error(`Error: slides directory not found: ${slidesDir}`);
  process.exit(1);
}

function readManifest() {
  const index = fs.readFileSync(indexFile, 'utf8');
  const manifestMatch = index.match(/const MANIFEST = \[([\s\S]*?)\];/);
  if (!manifestMatch) {
    throw new Error(`Could not find MANIFEST in ${indexFile}`);
  }
  const files = [...manifestMatch[1].matchAll(/["']([^"']+\.html)["']/g)]
    .map(match => match[1]);
  if (!files.length) {
    throw new Error(`MANIFEST in ${indexFile} does not list any slide files`);
  }
  return files;
}

function sha256(filePath) {
  return crypto.createHash('sha256').update(fs.readFileSync(filePath)).digest('hex');
}

async function render(slides) {
  fs.mkdirSync(screenshotsDir, { recursive: true });
  console.log(`Rendering ${slides.length} screenshots at ${width}x${height}...`);
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width, height } });
  for (let i = 0; i < slides.length; i++) {
    const slide = slides[i];
    const slidePath = path.join(slidesDir, slide);
    if (!fs.existsSync(slidePath)) {
      throw new Error(`Missing manifest slide: ${slidePath}`);
    }
    await page.goto(`file://${slidePath}`, { waitUntil: 'networkidle', timeout: 20000 });
    await page.addStyleTag({
      content: `body { transform: scale(${scale}); transform-origin: top left; }`,
    });
    await page.waitForTimeout(1500);
    const outPath = path.join(screenshotsDir, slide.replace('.html', '.png'));
    await page.screenshot({ path: outPath, clip: { x: 0, y: 0, width, height } });
    process.stdout.write(`  [${i + 1}/${slides.length}] ${slide}\n`);
  }
  await page.close();
  await browser.close();
}

function buildData(slides) {
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  const images = {};
  const metadata = {
    generatedAt: new Date().toISOString(),
    slideCount: slides.length,
    screenshotSize: { width, height },
    slides: [],
  };
  for (const slide of slides) {
    const screenshotPath = path.join(screenshotsDir, slide.replace('.html', '.png'));
    const slidePath = path.join(slidesDir, slide);
    if (!fs.existsSync(screenshotPath)) {
      throw new Error(`Missing screenshot for manifest slide: ${screenshotPath}`);
    }
    const screenshot = fs.readFileSync(screenshotPath);
    images[slide] = `data:image/png;base64,${screenshot.toString('base64')}`;
    const stat = fs.statSync(slidePath);
    metadata.slides.push({
      file: slide,
      sha256: sha256(slidePath),
      mtimeMs: Math.round(stat.mtimeMs),
    });
  }
  const out = [
    '// Auto-generated by scripts/build-slides-data.mjs. Do not edit by hand.',
    'window.SLIDE_DATA_BUILD = ' + JSON.stringify(metadata, null, 0) + ';',
    'window.SLIDE_IMAGES = ' + JSON.stringify(images, null, 0) + ';',
    '',
  ].join('\n');
  fs.writeFileSync(outFile, out);
  const sizeMB = (fs.statSync(outFile).size / 1024 / 1024).toFixed(2);
  console.log(`Wrote ${outFile} (${sizeMB} MB, ${slides.length} slides)`);
}

const slides = readManifest();
if (renderScreenshots) {
  await render(slides);
}
buildData(slides);
